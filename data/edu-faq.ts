export const eduFaqById: Record<string, EduFaq> = Object.fromEntries(eduFaq.map((f) => [f.id, f]))

/** 按 id 取问题，找不到返回 undefined（不抛异常，避免页面崩溃） */
export function getEduFaq(id: string): EduFaq | undefined {
  return eduFaqById[id]
}

/** 按对象筛选：'teacher' | 'student' | 'guardian' | 'school'，传空值返回全部 */
export function getEduFaqByAudience(audience?: EduFaq['audience']): EduFaq[] {
  if (!audience) return eduFaq
  return eduFaq.filter((f) => f.audience === audience)
}

/** 按分类筛选 */
export function getEduFaqByCategory(category: string): EduFaq[] {
  return eduFaq.filter((f) => f.category === category)
}